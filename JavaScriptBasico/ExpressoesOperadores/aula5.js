
let value = 1;

//Incremeneto (+=) - incrementa o valor da variável
value +=1;
console.log(value); // 2

//Decremento (-=) - decrementa o valor da variável
value -=1;
console.log(value); // 1

//Multiplicação (*=) - multiplica o valor da variável
value *=2;
console.log(value); // 2 

//Divisão (/=) - divide o valor da variável
value /=2;
console.log(value); // 1

//Resto da divisão (%=) - calcula o resto da divisão do valor da variável
value %=2;
console.log(value); // 1

