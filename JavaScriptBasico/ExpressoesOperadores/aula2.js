// Operadores aritméticos


let num1 = 10;
let num2 = 5;

//Soma
console.log(num1 + num2); // 15

//Subtração
console.log(num1 - num2); // 5

//Multiplicação
console.log(num1 * num2); // 50

//Divisão
console.log(num1 / num2); // 2

//Resto da divisão
console.log(num1 % num2); // 0 

//Potenciação
console.log(num1 ** num2); // 100000 

// Incremento
num1++;
console.log(num1); // 11 

// Decremento
num2--;
console.log(num2); // 4

// Concatenação
console.log("num1" + "num2"); // num1num2